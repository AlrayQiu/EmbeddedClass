void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim) {
  if (htim->Instance == htim9.Instance &&
      htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1) {
    ic2valuePwm = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);
    if (ic2valuePwm != 0) {
      recDuty = (HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_2) * 100.0) /
                ic2valuePwm;
      freq = (HAL_RCC_GetPCLK2Freq() * 2 / (htim9.Instance->PSC + 1)) /
             ic2valuePwm;
    } else {
      recDuty = 0;
      freq = 0;
    }
  }
}
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {
  if (GPIO_Pin == BTN_LEFT_Pin) {
    Duty -= dir;
    if (Duty < 100)
      Duty = 100;
  } else if (GPIO_Pin == BTN_RIGHT_Pin) {
    Duty += dir;

    if (Duty > 7900)
      Duty = 7900;
  }
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_4, Duty);
}
